"""One reviewed, explicitly licensed Chinese vocal download; isolated output.

Not a search crawler or production provider. Do not publish the audio URL.
"""
import datetime
import hashlib
import html
import json
import re
import subprocess
import time
from pathlib import Path
from urllib.parse import urljoin, urlsplit

import httpx
from mutagen.mp3 import MP3
from imageio_ffmpeg import get_ffmpeg_exe

ROOT = Path('.local/reports/twelve-sources-validation')


def main():
    page = (ROOT/'fma-vocal.html').read_text(encoding='utf-8')
    overlay = (ROOT/'fma-overlay.html').read_text(encoding='utf-8')
    assert 'https://creativecommons.org/licenses/by/4.0' in page
    assert 'Personal and commercial use allowed' in overlay
    assert 'I understand and agree' in overlay
    link = re.search(r'href="(https://freemusicarchive.org/track/[^" ]+/download/)"', overlay).group(1)
    directory = ROOT/'downloads'
    directory.mkdir(exist_ok=True)
    dest = directory/'Adeline Yeo (HP) - 风中的呢喃.mp3'
    report = {'time': datetime.datetime.now().astimezone().isoformat(),
              'title': '风中的呢喃 (FengZhongDeNeNan)', 'artist': 'Adeline Yeo (HP)',
              'source_page': 'https://freemusicarchive.org/music/adeline-yeo-hp/single/fengzhongdenenan/',
              'license': 'https://creativecommons.org/licenses/by/4.0',
              'license_evidence': 'fma-vocal.html and fma-overlay.html; personal/commercial use, attribution required',
              'attribution': '风中的呢喃 — Adeline Yeo (HP), Free Music Archive, CC BY 4.0; original bytes unchanged',
              'ai_disclosure': 'Page states this track or part of it was generated by AI',
              'expected_duration': 295, 'instrumental_on_page': False, 'requests': []}
    if dest.exists():
        raise FileExistsError('Existing research audio preserved; use its saved validation report')
    start = time.perf_counter()
    try:
        with httpx.Client(timeout=httpx.Timeout(20), trust_env=False, follow_redirects=False,
                          headers={'User-Agent': 'MelodyVaultResearch/0.1 (single licensed file download)'}) as client:
            url = link
            for _ in range(4):
                with client.stream('GET', url) as response:
                    report['requests'].append({'url':str(response.url),'status':response.status_code,
                                               'content_type':response.headers.get('content-type')})
                    response.raise_for_status() if not response.is_redirect else None
                    if response.is_redirect:
                        url = urljoin(url,response.headers['location'])
                        if urlsplit(url).path.startswith(('/login', '/register', '/signup')):
                            report['restriction'] = 'LOGIN_REQUIRED'
                            raise PermissionError('Normal download redirects to login; do not use embedded file URL')
                        if urlsplit(url).scheme != 'https' or urlsplit(url).hostname not in {'freemusicarchive.org','files.freemusicarchive.org'}:
                            raise ValueError('Unreviewed redirect; stopped')
                        continue
                    if not response.headers.get('content-type','').split(';')[0].startswith(('audio/','application/octet-stream')):
                        raise ValueError('Download returned non-audio content; no file saved')
                    size = 0
                    with dest.open('xb') as out:
                        for chunk in response.iter_bytes(65536):
                            size += len(chunk)
                            if size > 30_000_000 or time.perf_counter()-start > 120:
                                raise ValueError('Research size/time limit exceeded')
                            out.write(chunk)
                    if response.headers.get('content-length') and size != int(response.headers['content-length']):
                        raise ValueError('HTTP Content-Length mismatch')
                    break
            else: raise ValueError('Redirect limit exceeded')
        audio = MP3(dest)
        report.update(path=str(dest.resolve()),size=dest.stat().st_size,format='mp3',duration=audio.info.length,
                      sha256=hashlib.file_digest(dest.open('rb'),'sha256').hexdigest())
        if abs(audio.info.length-report['expected_duration']) > 2 or report['size'] < 100_000:
            raise ValueError('Duration/size mismatch, not validated as full track')
        proc = subprocess.run([get_ffmpeg_exe(),'-v','error','-xerror','-i',str(dest),'-map','0:a:0','-f','null','-'],capture_output=True,text=True,timeout=60)
        report.update(ffmpeg_exit=proc.returncode,ffmpeg_stderr=proc.stderr)
        if proc.returncode: raise ValueError('Full decoding failed')
        report['status'] = 'DOWNLOAD_SUCCESS'
    except Exception as error:
        report.update(status='DOWNLOAD_FAILED',error=type(error).__name__+': '+str(error))
    report['elapsed_seconds'] = round(time.perf_counter()-start,3)
    (ROOT/'phase-e.json').write_text(json.dumps(report,ensure_ascii=False,indent=2),encoding='utf-8')
    (directory/'ATTRIBUTION.txt').write_text(report['attribution']+'\n'+report['source_page']+'\n'+report['license']+'\nAI: '+report['ai_disclosure'],encoding='utf-8')
    print(json.dumps(report,ensure_ascii=False,indent=2))


if __name__ == '__main__':
    main()
